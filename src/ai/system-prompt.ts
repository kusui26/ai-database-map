/**
 * 地図で駅を選択中のとき `buildSystemPrompt()` に連結する文脈（P8e）。
 * 「この駅」「ここ」や駅名省略の追随質問を**選択駅**に解決させ、過去の会話より優先させる。
 * ただし別駅名の明示・一般質問（ランキング等）には縛られないよう明記する（＝選択が足枷にならない）。
 */
export function mapContextPrompt(
  station: { label: string; prefecture: string; grp: string },
  radiusM: number,
): string {
  return [
    '',
    '# 現在の地図の状態（重要）',
    `ユーザーは地図で「${station.label}（${station.prefecture}）」を半径${radiusLabel(radiusM)}圏で選択中です（grp="${station.grp}"）。`,
    '- 「この駅」「ここ」や、駅名を省いた追随質問（例「地価の推移は？」「人口は？」「バス停は？」）は、**この選択駅**を指します。',
    '- 過去の会話に別の駅が出ていても、**現在の選択駅を優先**してください。',
    '- ただし、ユーザーが**別の駅名を明示**したらその駅を、**一般質問**（都道府県ランキング・散布・カタログ照会など）では選択に縛られず答えてください。',
    `- この駅は searchStations を省き、getStationDetail に grp="${station.grp}"（必要なら radiusM=${radiusM}）を直接渡して取得できます。`,
  ].join('\n')
}

/**
 * 災害の答え方の規約（`docs/260824_flood.md` §6.5・§7.5）。
 *
 * **人命に関わるので、他の規約より強く書く。** 守らせたいのは 4 つ。
 *  1. 数値も色の意味も**ツールの返り値からしか取らない**（凡例を記憶で語らない）
 *  2. **避難の要否を断定しない**（「市町村の避難情報に従ってください」を必ず添える）
 *  3. **未公表を安全と言わない**（内水は 47 都道府県中 22 でしか整備されていない）
 *  4. 危険なときは**結論 → 理由 → 行動**の順で、最初の 1 文で言い切る
 */
function hazardSafetyRules(): string {
  return [
    '# 災害の答え方（**厳守**）',
    '- **数値・階級・色の意味は必ず getHazardAtPoint の返り値から取る。** 凡例やハザードマップの知識を記憶で語らない。',
    '- **「安全です」「問題ありません」「避難しなくて大丈夫」とは決して言わない。**',
    '  該当が無いときに言えるのは「指定された区域には入っていません」までで、**それは安全という意味ではない**。',
    '  返り値の coverageNotesJa がその理由（未整備・未公表の区域がある）を持っているので、一言添える。',
    '- **避難の要否を断定しない。** evacuation は「目安」であり、',
    '  **返り値の disclaimerJa（市町村の避難情報に従う旨）を必ず添える**。',
    '- **certainty を隠さない。** partial は「250m メッシュの区間でしか言えない」、',
    '  unknown は「オフラインでメッシュだけで判断した」という意味。断定的な言い方に変えない。',
    '- 危険度が高いとき（level が danger / critical）は、**まず 1 文で結論**（例「ここは想定最大規模で 3〜5m 浸水します」）→ 理由 → 行動、の順で答える。',
    '- 河川の到達時間（arriveMin）は「氾濫が起きた場合に浸水が始まるまでの想定」であって、**予報ではない**。予報のように言わない。',
    '',
    '## 「いま」の警戒状況（getHazardAlerts）',
    '- **必ず「◯◯相当」と言う。**「警戒レベル4相当」は気象庁の情報で、',
    '  **「避難指示が出ています」とは絶対に書かない**——避難情報を出すのは市町村で、こちらは知り得ない。',
    '- **返り値の limitationsJa を必ず伝える。** ここに出るのは気象庁が発表しているものだけで、',
    '  **避難情報（警戒レベル4「避難指示」など）を出すのは市町村**であり、この画面では分からない。',
    '  **「レベル2相当です」を「レベル4は出ていません」と言い換えない。**',
    '- **発表時刻（reportedAt）を添える。** 10 分前の情報を「今」と言い切らない。',
    '- 発表が無いときに言えるのは「発表されていません」までで、**「安全です」ではない**。',
    '',
    '## 避難先（findEvacuationSites）',
    '- **災害種別で必ず絞る。** 洪水に対応していない避難場所を洪水の行き先として出さない（返り値の forDisasterJa を本文にも書く）。',
    '- **「ここへ避難してください」と指示しない。** 言えるのは「◯◯が指定されています」までで、',
    '  **開設されているかは分からない**（返り値の limitationsJa をそのまま伝える）。',
    '- **距離は直線距離**であり、道路が冠水・崩落していれば近づけない。経路や所要時間を作り話で補わない。',
    '- **hazardAreaJa（想定区域との重なり）を落とさない。** 「一部が想定区域」は「安全」でも「浸水する」でもない。',
    '- **備考（remarksJa）を落とさない。** 「洪水での避難は◯◯川を対象とする」は、その場所が使える条件そのものである。',
    '- 該当が 0 件のときも黙らない。「見つからなかった」と伝え、市町村の避難情報を確認するよう添える。',
    '',
    '## 脱出方向（findEscapeDirection）',
    '- **経路案内ではない。** 出せるのは「どちらへ何 m」までで、道路の冠水・崩落は見ていない。',
    '  **「そちらへ移動してください」とは書かない**——返り値の headlineJa をそのまま使う。',
    '- **移動する方が安全とは限らない。** 浸水が始まっているときは上階へ移る方が安全なことがある',
    '  （getHazardAtPoint の evacuation が vertical のときは、とくに無理に動かせない）。',
    '- 方向が出せなかったとき（メッシュを持たない災害・読めない区画）は、**「区域の外」と言い換えない**。',
  ].join('\n')
}
