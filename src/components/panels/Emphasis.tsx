/**
 * `**強調**` だけを太字にして描く（`docs/260824_flood.md` §7.5）。
 *
 * ## なぜ要るのか
 *
 * ハザードの文言は**サーバが持つ**（カタログの `coverageNoteJa`・ドメインの限界の文）。
 * そこでは「**白いことは「内水が起きない」という意味ではありません。**」のように、
 * **いちばん誤解される 1 文**を強調して書いてある。ところがパネルは素のテキストとして描くので、
 * 画面には `**` がそのまま出ていた——**強調したい箇所ほど読みにくい**という逆転が起きていた。
 *
 * ## Markdown パーサではない
 *
 * 扱うのは `**…**` **1 種類だけ**。見出しもリンクも箇条書きも解釈しない。
 * 対応が取れていない `**` は**そのまま文字として出す**（勝手に消して意味を変えない）。
 * この 1 規則で足りるのは、サーバ側の文言が意図的にこれしか使っていないためである。
 */

import { Fragment } from 'react'

/** 強調の区切り。 */
const MARKER = '**'

/**
 * `**` で囲まれた区間だけを太字にする。
 * 区切りが奇数個（対応が取れていない）のときは、**何も解釈せず**そのまま返す。
 */
export function Emphasis({ text }: { text: string }) {
  const parts = text.split(MARKER)
  // 分割数が偶数 ＝ 区切りが奇数個 ＝ 閉じていない。素のまま出す。
  if (parts.length % 2 === 0) return <>{text}</>
  return (
    <>
      {parts.map((part, index) => (
        <Fragment key={`${index}-${part}`}>
          {index % 2 === 1 ? <strong className="font-semibold">{part}</strong> : part}
        </Fragment>
      ))}
    </>
  )
}
